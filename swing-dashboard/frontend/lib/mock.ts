/**
 * Peers sharing the instrument's theme. When the instrument's theme has no
 * other names in the loaded universe — BABA's "Consumer / China" has none among
 * the sixteen large caps — fall back to the index leaders by relative strength
 * and SAY which basis was used, rather than shipping an empty table.
 */
function peersFor(symbol: string, theme: string): { rows: DriverRow[]; basis: string } {
  const sameTheme = MOCK_DRIVERS.filter((r) => r.theme === theme);
  if (sameTheme.length >= 2) {
    return { rows: sameTheme.slice(0, 6), basis: `Names sharing this instrument's theme (${theme}).` };
  }
  return {
    rows: [...MOCK_DRIVERS].sort((a, b) => b.rs_vs_index_13w - a.rs_vs_index_13w).slice(0, 6),
    basis:
      `No other ${theme} name is in the loaded universe, so this is benchmarked against the ` +
      'index leaders by 13-week relative strength instead.',
  };
}

